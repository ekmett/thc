"""Generate concrete SIMD nodes from a small, pinned semantic/layout table.

Gradle writes build/generated/simd. --write updates the two explicitly marked
bytecode regions; --check verifies them. --verify-ghc checks machine contracts
against primOpSig/typePrimRep_maybe, without parsing printed Haskell types.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / 'scripts/simd-families.json'
# primitive scalar type, bit width, Java Vector type, Kotlin carrier accessor
LANES = {
    'Int8Rep': ('byte', 8, 'ByteVector', 'Long'),
    'Word8Rep': ('byte', 8, 'ByteVector', 'Long'),
    'Int16Rep': ('short', 16, 'ShortVector', 'Long'),
    'Word16Rep': ('short', 16, 'ShortVector', 'Long'),
    'Int32Rep': ('int', 32, 'IntVector', 'Long'),
    'Word32Rep': ('int', 32, 'IntVector', 'Long'),
    'Word64Rep': ('long', 64, 'LongVector', 'Long'),
    'Int64Rep': ('long', 64, 'LongVector', 'Long'),
    'FloatRep': ('float', 32, 'FloatVector', 'Float'),
    'DoubleRep': ('double', 64, 'DoubleVector', 'Double'),
}
UNSIGNED_MASK = {'Word8Rep': '0xffL', 'Word16Rep': '0xffffL', 'Word32Rep': '0xffff_ffffL'}
BINARY = {'plus': 'add', 'minus': 'subtract', 'times': 'multiply', 'divide': 'divide', 'min': 'min', 'max': 'max'}
VECTOR_METHOD = {'add': 'add', 'subtract': 'sub', 'multiply': 'mul', 'divide': 'div', 'min': 'min', 'max': 'max'}
LEGACY_INSERT = {'Int8X16', 'Word8X16', 'Int16X8', 'Word16X8', 'Int32X4', 'Word32X4', 'Int64X2', 'FloatX4', 'DoubleX2'}
OPS = {'pack', 'unpack', 'broadcast', 'negate', 'insert'} | BINARY.keys()
HEADER = ('// SPDX-FileCopyrightText: 2026 Edward Kmett\n'
          '// SPDX-License-Identifier: UPL-1.0 AND BSD-3-Clause\n\n'
          '// Generated by scripts/generate-simd-families.py; edit the family table/generator.\n')
HASKELL_HEADER = ('-- SPDX-FileCopyrightText: 2026 Edward Kmett',
                  '-- SPDX-License-Identifier: UPL-1.0 AND BSD-3-Clause', '')
QUERY = r'''let reps t = fmap (map show) (GHC.Types.RepType.typePrimRep_maybe t); tuple t = case GHC.Core.Type.splitTyConApp_maybe t of { Just (tc,_) -> GHC.Core.TyCon.isUnboxedTupleTyCon tc; _ -> False }; emit op = let (_,args,res,arity,_) = GHC.Builtin.PrimOps.primOpSig op; name = GHC.Types.Name.Occurrence.occNameString (GHC.Builtin.PrimOps.primOpOcc op) in if name `notElem` NAMES then pure () else case traverse reps (args++[res]) of { Nothing -> pure (); Just rs -> putStrLn (GHC.Types.Name.Occurrence.occNameString (GHC.Builtin.PrimOps.primOpOcc op) ++ "\t" ++ show arity ++ "\t" ++ show rs ++ "\t" ++ show (map tuple (args++[res]))) } in mapM_ emit GHC.Builtin.PrimOps.allThePrimOps'''


def families():
    data = json.loads(SPEC.read_text())
    if data['schema'] != 1 or data['ghc'] != '9.14.1':
        raise ValueError('Expected pinned SIMD family schema')
    names = set()
    for f in data['families']:
        if f['laneRep'] not in LANES or type(f['lanes']) is not int or f['lanes'] <= 0:
            raise ValueError('Unsupported lane contract')
        scalar, width, _, _ = LANES[f['laneRep']]
        stem = f['laneRep'].removesuffix('Rep')
        if f['element'] != stem + 'ElemRep' or f['name'] != f'{stem}X{f["lanes"]}' or f['bits'] != width * f['lanes'] or f['bits'] not in (128, 256, 512):
            raise ValueError('Contradictory vector identity/layout')
        if (f['name'] in names or not f['operations'] or len(set(f['operations'])) != len(f['operations'])
                or not set(f['operations']) <= OPS or type(f['newCarrier']) is not bool
                or type(f.get('composite', False)) is not bool):
            raise ValueError('Malformed SIMD operation family')
        if f.get('composite') and (not f['newCarrier'] or not {'pack', 'unpack'} <= set(f['operations'])):
            raise ValueError('Composite fixture needs a new carrier and pack/unpack')
        if 'divide' in f['operations'] and scalar not in ('float', 'double'):
            raise ValueError('Integer vector division is a separate semantic family')
        if 'negate' in f['operations'] and f['laneRep'].startswith('Word'):
            raise ValueError('No unsigned vector negation primop')
        if 'insert' in f['operations'] and not f['newCarrier'] and f['name'] not in LEGACY_INSERT:
            raise ValueError('Insert requires a known concrete lane carrier')
        names.add(f['name'])
    return data['families']


def contracts(fs):
    result = {}
    for f in fs:
        vector = [f'VecRep {f["lanes"]} {f["element"]}']
        lane = [f['laneRep']]
        packed = lane * f['lanes']
        for op in f['operations']:
            args = [packed] if op == 'pack' else [lane] if op == 'broadcast' else [vector, lane, ['IntRep']] if op == 'insert' else [vector] * (2 if op in BINARY else 1)
            result[op + f['name'] + '#'] = {'arity':len(args), 'reps': args + [packed if op == 'unpack' else vector], 'tuples': [op == 'pack'] * len(args) + [op == 'unpack']}
    return result


def verify_ghc(fs):
    ghc = os.environ.get('GHC', 'ghc')
    if subprocess.check_output([ghc, '--numeric-version'], text=True).strip() != '9.14.1':
        raise ValueError('GHC 9.14.1 required')
    rows = subprocess.check_output([ghc, '-ignore-dot-ghci', '-package', 'ghc', '-e', QUERY.replace('NAMES', json.dumps(list(contracts(fs))))], text=True)
    actual = {}
    for line in rows.splitlines():
        name, arity, reps, tuples = line.split('\t')
        actual[name] = {'arity': int(arity), 'reps': json.loads(reps), 'tuples':json.loads(tuples.replace('True','true').replace('False','false'))}
    expected = contracts(fs)
    for name, proof in expected.items():
        if actual.get(name) != proof:
            raise ValueError(f'GHC machine contract disagrees for {name}: {actual.get(name)} != {proof}')
    print(f'Verified {len(expected)} exact SIMD contracts with pinned GHC APIs')


def carrier(f):
    n = f['name']; count = f['lanes']; scalar, _, vector, _ = LANES[f['laneRep']]
    primitive = scalar.capitalize()
    fields = ', '.join(f'@JvmField val lane{i}: {primitive}' for i in range(count))
    vec = f'{vector}.broadcast({vector}.SPECIES_{f["bits"]}, lane0)' + ''.join(f'.withLane({i}, lane{i})' for i in range(1, count))
    unsigned_extrema = f['laneRep'].startswith('Word') and any(op in ('min', 'max') for op in f['operations'])
    lines = [HEADER, 'package thc.runtime', f'import jdk.incubator.vector.{vector}',
             *(['import jdk.incubator.vector.VectorOperators'] if unsigned_extrema else []),
             '/** Exact durable primitive lanes; transient Vector API storage never escapes here. */',
             f'class {n}({fields}) {{', f'    private fun vector(): {vector} = {vec}',
             '    companion object {',
             f'        private fun lanes(v: {vector}): {n} = {n}('+', '.join(f'v.lane({i})' for i in range(count))+')',
             f'        @JvmStatic fun broadcast(x: {primitive}): {n} = {n}('+', '.join('x' for _ in range(count))+')']
    for op in f['operations']:
        if op in BINARY:
            method = BINARY[op]
            expression = (f'a.vector().lanewise(VectorOperators.U{op.upper()}, b.vector())'
                          if unsigned_extrema and op in ('min', 'max') else
                          f'a.vector().{VECTOR_METHOD[method]}(b.vector())')
            lines.append(f'        @JvmStatic fun {method}(a: {n}, b: {n}): {n} = lanes({expression})')
        elif op == 'negate':
            lines.append(f'        @JvmStatic fun negate(a: {n}): {n} = lanes(a.vector().neg())')
        elif op == 'insert':
            lines += [f'        @JvmStatic fun insert(a: {n}, value: {primitive}, index: Long): {n} {{',
                      f'            if (index < 0L || index >= {count}L) fault("Invalid {n} lane index")',
                      f'            return {n}(' + ', '.join(f'if (index == {i}L) value else a.lane{i}' for i in range(count)) + ')',
                      '        }']
    return '\n'.join(lines + ['    }', '}']) + '\n'


def transport_code(fs):
    """Concrete lane codecs: no reflection, payload arrays, or boxed lane lists."""
    fields = 'first second third fourth fifth sixth seventh eighth ninth tenth eleventh twelfth thirteenth fourteenth fifteenth sixteenth'.split()
    lines = [HEADER, 'package thc.runtime',
             'import com.oracle.truffle.api.frame.VirtualFrame',
             'import com.oracle.truffle.api.bytecode.BytecodeNode',
             'import com.oracle.truffle.api.bytecode.LocalAccessor',
             '', 'internal object GeneratedVectorTransport {']
    lines += [f'    private val shape{f["name"]} = CoreVector({f["lanes"]}, "{f["element"]}")' for f in fs]
    for bytecode in (False, True):
        parameters = ('bytecode: BytecodeNode, frame: VirtualFrame, slots: Array<LocalAccessor>' if bytecode
                      else 'frame: VirtualFrame, slots: IntArray')
        lines += [f'    fun write(shape: CoreVector, {parameters}, offset: Int, raw: Any?) {{',
                  '        when (shape) {']
        for f in fs:
            n, count = f['name'], f['lanes']
            scalar, _, _, access = LANES[f['laneRep']]
            lines += [f'            shape{n} -> {{',
                      f'                val value = raw as? {n} ?: fault("Expected exact {n}# carrier")']
            for i in range(count):
                lane = (f'value.lane{i}' if f['newCarrier'] else f'value.lane({i})'
                        if n in ('FloatX4', 'DoubleX2') else f'value.{fields[i]}')
                if access == 'Long' and scalar != 'long':
                    lane += '.toLong()'
                    if f['laneRep'] in UNSIGNED_MASK:
                        lane += ' and ' + UNSIGNED_MASK[f['laneRep']]
                setter = (f'slots[offset + {i}].set{access}(bytecode, frame, {lane})' if bytecode
                          else f'FrameAccess.write{access}(frame, slots[offset + {i}], {lane})')
                lines.append('                ' + setter)
            lines += ['            }']
        lines += ['            else -> fault("Unsupported vector transport shape")', '        }', '    }',
                  f'    fun read(shape: CoreVector, {parameters}, offset: Int): Any = when (shape) {{']
        for f in fs:
            n, count = f['name'], f['lanes']
            scalar, _, _, access = LANES[f['laneRep']]
            values = []
            for i in range(count):
                value = (f'slots[offset + {i}].get{access}(bytecode, frame)' if bytecode
                         else f'frame.get{access}(slots[offset + {i}])')
                if scalar in ('byte', 'short', 'int'):
                    value += f'.to{scalar.capitalize()}()'
                values.append(value)
            constructor = n + '.pack' if n in ('FloatX4', 'DoubleX2') else n
            lines.append(f'        shape{n} -> {constructor}(' + ', '.join(values) + ')')
        lines += ['        else -> fault("Unsupported vector transport shape")', '    }']
    return '\n'.join(lines + ['}']) + '\n'


def proof_code(fs):
    lines = [HEADER, 'package thc.runtime\n', 'internal object GeneratedVectors {',
             '    private val index = CoreRepresentation(CoreKind.LONG, true, true, listOf("IntRep"))']
    for f in fs:
        n=f['name']; kind=LANES[f['laneRep']][3].upper();count=f['lanes'];rep=f['laneRep']
        lines += [f'    val vector{n} = CoreVector({count}, "{f["element"]}")',
                  f'    val proof{n} = CoreRepresentation(CoreKind.VECTOR, true, true, listOf("VecRep {count} {f["element"]}"), vector = vector{n})',
                  f'    private val lane{n} = CoreRepresentation(CoreKind.{kind}, true, true, listOf("{rep}"))',
                  f'    val unpacked{n} = CoreRepresentation(CoreKind.UNKNOWN, true, true, List({count}) {{ "{rep}" }}, List({count}) {{ lane{n} }})']
    allops=list(contracts(fs))
    lines += ['    val operations = setOf('+', '.join('"'+name+'"' for name in allops)+')',
              '    fun supports(vector: CoreVector): Boolean = '+ ' || '.join(f'vector == vector{f["name"]}' for f in fs if f['newCarrier']),
              '    fun validate(name: String, arguments: List<CoreRepresentation>, result: CoreRepresentation) {',
              '        val contract = when (name) {']
    for f in fs:
        n=f['name']
        for op in f['operations']:
            args=f'unpacked{n}' if op=='pack' else f'lane{n}' if op=='broadcast' else f'proof{n}, lane{n}, index' if op=='insert' else ', '.join([f'proof{n}']*(2 if op in BINARY else 1))
            result=f'unpacked{n}' if op=='unpack' else f'proof{n}'
            lines.append(f'            "{op}{n}#" -> Pair(listOf({args}), {result})')
    lines += ['            else -> throw UnsupportedCore("Unsupported generated vector primitive $name")','        }',
              '        CoreVectors.validateSignature(name, arguments, result, contract.first, contract.second)', '    }',
              '    fun expression(name: String, arguments: Array<Expr>, allocate: (Int) -> IntArray): Expr = when (name) {']
    for f in fs:
        n=f['name']
        for op in f['operations']:
            expr=f'Generated{n}Pack(arguments[0], allocate({f["lanes"]}))' if op=='pack' else f'Generated{n}Unpack(arguments[0])' if op=='unpack' else f'Generated{n}Operation(name, arguments)'
            lines.append(f'        "{op}{n}#" -> {expr}')
    lines += ['        else -> throw UnsupportedCore("Unsupported generated vector primitive $name")','    }','}']
    return '\n'.join(lines)+'\n'


def legacy_insert_code(fs):
    fields = 'first second third fourth fifth sixth seventh eighth ninth tenth eleventh twelfth thirteenth fourteenth fifteenth sixteenth'.split()
    lines = [HEADER, 'package thc.runtime', '',
             '/** Replace one lane without changing the existing carrier representation. */',
             'internal object GeneratedVectorInsert {']
    for f in fs:
        if f['newCarrier'] or 'insert' not in f['operations']:
            continue
        n, count = f['name'], f['lanes']
        primitive = LANES[f['laneRep']][0].capitalize()
        vector_backed = n in ('FloatX4', 'DoubleX2')
        constructor = n + '.pack' if vector_backed else n
        lanes = [f'a.lane({i})' if vector_backed else f'a.{fields[i]}' for i in range(count)]
        lines += [f'    @JvmStatic fun insert(a: {n}, value: {primitive}, index: Long): {n} {{',
                  f'        if (index < 0L || index >= {count}L) fault("Invalid {n} lane index")',
                  f'        return {constructor}(' + ', '.join(f'if (index == {i}L) value else {lane}' for i, lane in enumerate(lanes)) + ')',
                  '    }']
    return '\n'.join(lines + ['}']) + '\n'


def ast_code(fs):
    lines=[HEADER,'package thc.runtime\n','import com.oracle.truffle.api.CompilerDirectives.CompilationFinal','import com.oracle.truffle.api.frame.VirtualFrame\n']
    for f in fs:
        n=f['name'];count=f['lanes'];scalar,_,_,access=LANES[f['laneRep']]; cast=f'.to{scalar.capitalize()}()' if scalar in ('byte', 'short', 'int') else ''
        if 'pack' in f['operations']:
            lines += [f'internal class Generated{n}Pack(@field:Child private var argument: Expr,',
                      '    @field:CompilationFinal(dimensions = 1) private val slots: IntArray) : Expr() {',
                      f'    init {{ representation = GeneratedVectors.proof{n} }}',
                      f'    override fun execute(frame: VirtualFrame): {n} {{', '        argument.executeTuple(frame, slots)',
                      f'        return {n}('+', '.join(f'frame.get{access}(slots[{i}]){cast}' for i in range(count))+')','    }','}']
        if 'unpack' in f['operations']:
            lines += [f'internal class Generated{n}Unpack(@field:Child private var argument: Expr) : Expr() {{',
                      f'    init {{ representation = GeneratedVectors.unpacked{n} }}',
                      '    override fun execute(frame: VirtualFrame): Nothing = fault("Vector unpack requires a tuple destination")',
                      '    override fun executeTuple(frame: VirtualFrame, slots: IntArray, offset: Int): Any? {',
                      f'        val value = argument.execute(frame) as? {n} ?: fault("Expected {n}#")']
            mask = UNSIGNED_MASK.get(f['laneRep'])
            for i in range(count):
                lane = (f'value.lane{i}.toLong() and {mask}' if mask
                        else f'value.lane{i}.toLong()' if cast else f'value.lane{i}')
                lines.append(f'        FrameAccess.write{access}(frame, slots[offset + {i}], {lane})')
            lines += ['        return null','    }','}']
        ops=[op for op in f['operations'] if op not in ('pack','unpack')]
        lines += [f'internal class Generated{n}Operation(name: String, @field:Children private var arguments: Array<Expr>) : Expr() {{',
                  '    private val operation = when (name) {']
        lines += [f'        "{op}{n}#" -> {i}' for i,op in enumerate(ops)]
        lines += [f'        else -> throw RuntimeFault("Invalid {n} operation")','    }',
                  f'    init {{ representation = GeneratedVectors.proof{n} }}',
                  f'    override fun execute(frame: VirtualFrame): {n} = when (operation) {{']
        for i,op in enumerate(ops):
            expr=f'{n}.broadcast(arguments[0].executeRequired{access}(frame){cast})' if op=='broadcast' else f'{n}.negate(vector(frame, 0))' if op=='negate' else f'{n if f["newCarrier"] else "GeneratedVectorInsert"}.insert(vector(frame, 0), arguments[1].executeRequired{access}(frame){cast}, arguments[2].executeRequiredLong(frame))' if op=='insert' else f'{n}.{BINARY[op]}(vector(frame, 0), vector(frame, 1))'
            lines.append(f'        {i} -> {expr}')
        lines += [f'        else -> fault("Invalid {n} operation")','    }',
                  f'    private fun vector(frame: VirtualFrame, index: Int): {n} = arguments[index].execute(frame) as? {n} ?: fault("Expected {n}#")','}\n']
    return '\n'.join(lines)+'\n'


def bytecode_nodes(fs):
    lines=[]
    for f in fs:
        n=f['name'];count=f['lanes'];scalar,_,_,access=LANES[f['laneRep']];prim=access.lower(); cast=f'({scalar}) ' if scalar in ('byte', 'short', 'int') else ''
        for op in f['operations']:
            title=op.capitalize(); node=f'Generated{n}{title}'
            if op=='unpack':
                lines += ['    @Operation']+[f'    @ConstantOperand(type = LocalAccessor.class, name = "lane{i}")' for i in range(count)]
                lines += [f'    public static final class {node} {{',
                          '        @Specialization public static void apply(VirtualFrame frame, '+', '.join(f'LocalAccessor lane{i}' for i in range(count))+f', {n} value, @Bind("$node") Node node) {{',
                          '            BytecodeNode bytecode = ((BytecodeRoot) node.getRootNode()).getBytecodeNode();']
                mask = UNSIGNED_MASK.get(f['laneRep'])
                lane = (lambda i: f'value.lane{i} & {mask}' if mask
                        else f'value.lane{i}')
                lines += [f'            lane{i}.set{access}(bytecode, frame, {lane(i)});' for i in range(count)]
                lines += ['        }','    }']
            else:
                if op=='pack':
                    params=', '.join(f'{prim} lane{i}' for i in range(count)); expr=f'new {n}('+', '.join(cast+f'lane{i}' for i in range(count))+')'
                elif op=='broadcast':params=f'{prim} value';expr=f'{n}.broadcast({cast}value)'
                elif op=='negate':params=f'{n} value';expr=f'{n}.negate(value)'
                elif op=='insert':params=f'{n} vector, {prim} value, long index';expr=f'{n if f["newCarrier"] else "GeneratedVectorInsert"}.insert(vector, {cast}value, index)'
                else:params=f'{n} left, {n} right';expr=f'{n}.{BINARY[op]}(left, right)'
                lines += [f'    @Operation public static final class {node} {{',f'        @Specialization public static {n} apply({params}) {{ return {expr}; }}','    }']
    return '\n'.join(lines)+'\n'


def bytecode_emitter(fs):
    lines=['    private fun generatedVectorPrimitive(name: String, operands: List<Expression>): Expression = when (name) {']
    for f in fs:
        n=f['name'];count=f['lanes']
        for op in f['operations']:
            node=f'Generated{n}{op.capitalize()}'
            if op=='unpack':
                lines += [f'        "{op}{n}#" -> tupleExpression(GeneratedVectors.unpacked{n}) {{ e, destination ->',
                          f'            e.builder.begin{node}('+', '.join(f'destination[{i}]' for i in range(count))+')',
                          '            operands[0].emit(e)',f'            e.builder.end{node}()','        }']
            else:
                lines += [f'        "{op}{n}#" -> ProvenExpression(Expression {{ e ->','            val b = e.builder']
                if op=='pack':
                    lines += ['            b.beginBlock()',f'            val lanes = List({count}) {{ b.createLocal() }}','            operands[0].emitTuple(e, lanes)',f'            b.begin{node}(); lanes.forEach(b::emitLoadLocal); b.end{node}()','            b.endBlock()']
                else:
                    lines += [f'            b.begin{node}(); operands.forEach {{ it.emit(e) }}; b.end{node}()']
                lines += [f'        }}, GeneratedVectors.proof{n})']
    lines += ['        else -> throw UnsupportedCore("Unsupported generated vector primitive $name")','    }']
    return '\n'.join(lines)+'\n'


def fixture_sources(fs):
    """Real scalar-entry Haskell; vectors never cross a function boundary."""
    extrema = [op + f['name'] + '#' for f in fs for op in f['operations'] if op in ('min', 'max')]
    source = [*HASKELL_HEADER, '{-# LANGUAGE MagicHash, UnboxedTuples #-}', 'module GeneratedSimdFamilies where',
              'import GHC.Exts', *(['import GHC.Prim (' + ', '.join(extrema) + ')'] if extrema else []), '',
              '-- NaN payload selection is not part of arithmetic primop semantics.',
              '-- All non-NaNs are observed as exact bits, including signed zero.',
              '{-# INLINE bitsFloat #-}', 'bitsFloat :: Float# -> Int#',
              'bitsFloat value = case neFloat# value value of',
              '  1# -> 2143289344#',
              '  _ -> word2Int# (word32ToWord# (castFloatToWord32# value))',
              '{-# INLINE bitsDouble #-}', 'bitsDouble :: Double# -> Int#',
              'bitsDouble value = case value /=## value of',
              '  1# -> 9221120237041090560#',
              '  _ -> word2Int# (word64ToWord# (castDoubleToWord64# value))', '']
    convert = {
        'Int8Rep': lambda x: f'intToInt8# ({x})',
        'Word8Rep': lambda x: f'wordToWord8# (int2Word# ({x}))',
        'Int16Rep': lambda x: f'intToInt16# ({x})',
        'Word16Rep': lambda x: f'wordToWord16# (int2Word# ({x}))',
        'Int32Rep': lambda x: f'intToInt32# ({x})',
        'Word32Rep': lambda x: f'wordToWord32# (int2Word# ({x}))',
        'Int64Rep': lambda x: f'intToInt64# ({x})',
        'Word64Rep': lambda x: f'wordToWord64# (int2Word# ({x}))',
        'FloatRep': lambda x: f'castWord32ToFloat# (wordToWord32# (int2Word# ({x})))',
        'DoubleRep': lambda x: f'castWord64ToDouble# (wordToWord64# (int2Word# ({x})))',
    }
    observe = {'Int8Rep': 'int8ToInt#', 'Int16Rep': 'int16ToInt#', 'Int32Rep': 'int32ToInt#', 'Int64Rep': 'int64ToInt#',
               'Word64Rep': 'word2Int# . word64ToWord#', 'FloatRep': 'bitsFloat', 'DoubleRep': 'bitsDouble'}
    names = []
    for family in fs:
        n = family['name']; count = family['lanes']; rep = family['laneRep']
        operations = [op for op in family['operations'] if op not in ('pack', 'unpack')]
        def observe_lane(i):
            return (f'word2Int# (word{rep[4:-3]}ToWord# p{i})' if rep.startswith('Word') else f'{observe[rep]} p{i}')
        def selected_lane(op, lane):
            if op == 'broadcast':
                vector = f'broadcast{n}# ({convert[rep]("a")})'
            else:
                left = f'pack{n}# (# ' + ', '.join(convert[rep](f'a +# {i * 104729}#') for i in range(count)) + ' #)'
                right = f'pack{n}# (# ' + ', '.join(convert[rep](f'b -# {i * 7919}#') for i in range(count)) + ' #)'
                vector = f'{op}{n}# ({left})' + (f' ({right})' if op in BINARY else '')
                if op == 'insert':
                    vector += f' ({convert[rep]("b")}) {lane}#'
            value = observe_lane(lane)
            return f'case unpack{n}# ({vector}) of {{ (# '+', '.join(f'p{i}' for i in range(count))+f' #) -> {value} }}'
        if family.get('composite'):
            name = n[0].lower() + n[1:] + 'Composite'; worker = name + 'Worker'; names.append(name)
            source += [f'{{-# OPAQUE {worker} #-}}', f'{worker} :: Int# -> Int# -> Int# -> Int#',
                       f'{worker} selector a b = case selector of']
            for op_index, op in enumerate(operations):
                for lane in range(count):
                    source.append(f'  {op_index * count + lane}# -> {selected_lane(op, lane)}')
            source += ['  _ -> 0#', f'{name} :: Int# -> Int# -> Int# -> Int#',
                       f'{name} selector a b = case {worker} selector a b of value -> value +# 17#', '']
            continue
        for op in operations:
            name = op + n; worker = name + 'Worker'; names.append(name)
            source += [f'{{-# OPAQUE {worker} #-}}', f'{worker} :: Int# -> Int# -> Int# -> Int#',
                       f'{worker} lane a b =']
            if op == 'broadcast':
                vector = f'broadcast{n}# ({convert[rep]("a")})'
            else:
                left = f'pack{n}# (# ' + ', '.join(convert[rep](f'a +# {i * 104729}#') for i in range(count)) + ' #)'
                right = f'pack{n}# (# ' + ', '.join(convert[rep](f'b -# {i * 7919}#') for i in range(count)) + ' #)'
                vector = f'{op}{n}# ({left})' + (f' ({right})' if op in BINARY else '')
                if op == 'insert':
                    vector += f' ({convert[rep]("b")}) lane'
            source += [f'  case unpack{n}# ({vector}) of',
                       '    (# ' + ', '.join(f'p{i}' for i in range(count)) + ' #) -> case lane of']
            for i in range(count):
                value = observe_lane(i)
                source.append(f'      {str(i)+"#" if i < count-1 else "_"} -> {value}')
            source += [f'{name} :: Int# -> Int# -> Int# -> Int#',
                       f'{name} lane a b = case {worker} lane a b of value -> value +# 17#', '']
    native = [*HASKELL_HEADER, '{-# LANGUAGE MagicHash #-}', 'module Main where', 'import GHC.Exts',
              'import Data.Bits (finiteBitSize)', 'import GeneratedSimdFamilies', '',
              'emit :: String -> (Int# -> Int# -> Int# -> Int#) -> Int -> Int -> Int -> IO ()',
              'emit name f lane@(I# k) a@(I# x) b@(I# y) =',
              '  putStrLn (name ++ "\\t" ++ show lane ++ "\\t" ++ show a ++ "\\t" ++ show b ++ "\\t" ++ show (I# (f k x y)))',
              'dispatch :: [String] -> IO ()', 'dispatch [name, lane, a, b] = case name of']
    native += [f'  "{name}" -> emit name {name} (read lane) (read a) (read b)' for name in names]
    native += ['  _ -> error "unknown SIMD family entry"', 'dispatch _ = error "invalid input"',
               'main :: IO ()', 'main = if finiteBitSize (0 :: Int) /= 64 then error "Requires 64-bit Int"',
               '       else getContents >>= mapM_ (dispatch . words) . lines']
    return {'fixtures/GeneratedSimdFamilies.hs': '\n'.join(source)+'\n',
            'fixtures/GeneratedSimdFamiliesNative.hs': '\n'.join(native)+'\n'}


def smoke_entries(fs):
    return [(f, op) for f in fs for op in f['operations'] if op not in ('pack', 'unpack')]


def smoke_groups(fs):
    """Bound compiled size by lane work, splitting only oversized families."""
    groups = [[]]
    legacy = []
    cost = index = 0
    for family in fs:
        indices = []
        for operation in family['operations']:
            if operation in ('pack', 'unpack'):
                continue
            (legacy if operation == 'insert' and not family['newCarrier'] else indices).append(index)
            index += 1
        limit = 112 // family['lanes']
        for start in range(0, len(indices), limit):
            chunk = indices[start:start + limit]
            lanes = family['lanes'] * len(chunk)
            if groups[-1] and cost + lanes > 112:
                groups.append([])
                cost = 0
            groups[-1].extend(chunk)
            cost += lanes
    if legacy:
        groups.append(legacy)
    return {f'simdSmoke{i}': indices for i, indices in enumerate(groups)}


def smoke_sources(fs):
    """Bounded composite drivers; the native scalar oracle needs no SIMD ISA."""
    convert = {
        'Int8Rep': lambda x: f'intToInt8# ({x})',
        'Word8Rep': lambda x: f'wordToWord8# (int2Word# ({x}))',
        'Int16Rep': lambda x: f'intToInt16# ({x})',
        'Word16Rep': lambda x: f'wordToWord16# (int2Word# ({x}))',
        'Int32Rep': lambda x: f'intToInt32# ({x})',
        'Word32Rep': lambda x: f'wordToWord32# (int2Word# ({x}))',
        'Int64Rep': lambda x: f'intToInt64# ({x})',
        'Word64Rep': lambda x: f'wordToWord64# (int2Word# ({x}))',
        'FloatRep': lambda x: f'castWord32ToFloat# (wordToWord32# (int2Word# ({x})))',
        'DoubleRep': lambda x: f'castWord64ToDouble# (wordToWord64# (int2Word# ({x})))',
    }
    def observe(rep, value, raw=False):
        if rep.startswith('Word'):
            return f'word2Int# (word{rep[4:-3]}ToWord# ({value}))'
        if rep.startswith('Int'):
            return f'int{rep[3:-3]}ToInt# ({value})'
        if raw:
            width = '32' if rep == 'FloatRep' else '64'
            stem = rep.removesuffix('Rep')
            return f'word2Int# (word{width}ToWord# (cast{stem}ToWord{width}# ({value})))'
        if rep == 'FloatRep':
            return f'case {value} of v -> case neFloat# v v of {{ 1# -> 2143289344#; _ -> word2Int# (word32ToWord# (castFloatToWord32# v)) }}'
        return f'case {value} of v -> case v /=## v of {{ 1# -> 9221120237041090560#; _ -> word2Int# (word64ToWord# (castDoubleToWord64# v)) }}'
    def header(name):
        extrema = [op + f['name'] + '#' for f in fs for op in f['operations'] if op in ('min', 'max')]
        return [*HASKELL_HEADER, '{-# LANGUAGE MagicHash, UnboxedTuples #-}', f'module {name} where',
                'import GHC.Exts', *(['import GHC.Prim (' + ', '.join(extrema) + ')'] if name == 'GeneratedSimdSmoke' and extrema else []), '']
    def signature(entry):
        return [f'{entry} :: Int# -> Int# -> Int# -> Int#',
                f'{entry} selector a b = case quotInt# selector 256# of']
    groups = smoke_groups(fs)
    owners = {index: name for name, indices in groups.items() for index in indices}
    drivers = {name: signature(name) for name in groups}
    scalar = header('GeneratedSimdSmokeScalar') + signature('scalarSmoke')
    for index, (f, op) in enumerate(smoke_entries(fs)):
        vector = drivers[owners[index]]
        n, count, rep = f['name'], f['lanes'], f['laneRep']
        lane = 'remInt# selector 16#'
        left = f'pack{n}# (# ' + ', '.join(convert[rep](f'a +# {i * 104729}#') for i in range(count)) + ' #)'
        right = f'pack{n}# (# ' + ', '.join(convert[rep](f'b -# {i * 7919}#') for i in range(count)) + ' #)'
        value = (f'broadcast{n}# ({convert[rep]("a")})' if op == 'broadcast' else
                 f'{op}{n}# ({left})' + (f' ({right})' if op in BINARY else ''))
        inserted = 'remInt# (quotInt# selector 16#) 16#'
        if op == 'insert':
            value += f' ({convert[rep]("b")}) ({inserted})'
        vector += [f'  {index}# -> case unpack{n}# ({value}) of',
                   '    (# ' + ', '.join(f'p{i}' for i in range(count)) + f' #) -> case {lane} of']
        vector += [f'      {str(i) + "#" if i < count - 1 else "_"} -> {observe(rep, f"p{i}", op == "insert")}' for i in range(count)]
        left = convert[rep]('a' if op == 'broadcast' else f'a +# (({lane}) *# 104729#)')
        right = convert[rep](f'b -# (({lane}) *# 7919#)')
        stem = rep.removesuffix('Rep')
        primitive = (dict(plus='(+##)', minus='(-##)', times='(*##)', divide='(/##)', negate='negateDouble#').get(op)
                     if rep == 'DoubleRep' else
                     ('sub' if op == 'minus' and rep not in ('FloatRep', 'DoubleRep') else op) + stem + '#')
        if op == 'insert':
            scalar.append(f'  {index}# -> case ({lane}) ==# ({inserted}) of {{ 1# -> {observe(rep, convert[rep]("b"), True)}; _ -> {observe(rep, left, True)} }}')
        elif op in ('min', 'max'):
            # GHC has vector extrema but no corresponding scalar min/max primops.
            first, second = (left, right) if op == 'min' else (right, left)
            scalar.append(f'  {index}# -> case lt{stem}# ({left}) ({right}) of {{ 1# -> {observe(rep, first)}; _ -> {observe(rep, second)} }}')
        else:
            value = left if op == 'broadcast' else f'{primitive} ({left})' + (f' ({right})' if op in BINARY else '')
            scalar.append(f'  {index}# -> {observe(rep, value)}')
    vector = header('GeneratedSimdSmoke')
    for driver in drivers.values():
        vector += driver + ['  _ -> 0#', '']
    scalar += ['  _ -> 0#']
    outputs = {'fixtures/GeneratedSimdSmoke.hs': '\n'.join(vector) + '\n',
               'fixtures/GeneratedSimdSmokeScalar.hs': '\n'.join(scalar) + '\n'}
    for compare_vector in (False, True):
        main = [*HASKELL_HEADER, '{-# LANGUAGE MagicHash #-}', 'module Main where',
                'import GHC.Exts', 'import Data.Bits (finiteBitSize)', 'import GeneratedSimdSmokeScalar']
        if compare_vector:
            main += ['import GeneratedSimdSmoke']
        main += ['emit :: [String] -> IO ()', 'emit [name, selector, left, right] =',
                 '  case (read selector, read left, read right) of',
                 '    (I# k, I# a, I# b) ->',
                 '      let answer = I# (scalarSmoke k a b)']
        if compare_vector:
            main += ['          actual = case name of']
            main += [f'            "{name}" -> I# ({name} k a b)' for name in groups]
            main += ['            _ -> error "Unknown SIMD smoke entry"', '      in',
                     '        if answer /= actual then error "Native SIMD/scalar mismatch" else']
        else:
            main += ['      in', f'        if name `notElem` {json.dumps(list(groups))} then error "Unknown SIMD smoke entry" else']
        main += ['          putStrLn (name ++ "\\t" ++ selector ++ "\\t" ++ left ++ "\\t" ++ right ++ "\\t" ++ show answer)',
                 'emit _ = error "Invalid SIMD smoke input"', 'main :: IO ()',
                 'main = if finiteBitSize (0 :: Int) /= 64 then error "Requires 64-bit Int"',
                 '       else getContents >>= mapM_ (emit . words) . lines']
        suffix = 'Vector' if compare_vector else 'Scalar'
        outputs[f'fixtures/GeneratedSimdSmoke{suffix}Native.hs'] = '\n'.join(main) + '\n'
    return outputs


def region(path, content, write):
    begin='    // BEGIN GENERATED SIMD FAMILIES\n';end='    // END GENERATED SIMD FAMILIES\n'
    source=path.read_text()
    if source.count(begin)!=1 or source.count(end)!=1:raise ValueError(f'Missing unique generated region in {path}')
    before,tail=source.split(begin);old,after=tail.split(end)
    if write:path.write_text(before+begin+content+end+after)
    elif old!=content:raise ValueError(f'Stale generated region: {path}; run generator --write')


